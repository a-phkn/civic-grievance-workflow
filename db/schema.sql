BEGIN;

DROP VIEW     IF EXISTS v_complaint_progress, v_task_overdue CASCADE;
DROP TABLE    IF EXISTS audit_log, task_dependency, task, agency_task_type,
                        complaint, app_user, agency CASCADE;

-- ---------------------------------------------------------------------
-- 1. AGENCY                                   (ER: entity AGENCY)
-- ---------------------------------------------------------------------
CREATE TABLE agency (
    agency_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_name  VARCHAR(100) NOT NULL UNIQUE,          -- schema: UQ
    description  TEXT
);

-- ---------------------------------------------------------------------
-- 2. APP_USER                                 (ER: entity APP_USER)
--    HAS_USER  APP_USER N : 1 AGENCY, partial participation
--    -> agency_id is nullable; only AGENCY_STAFF belong to an agency.
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL UNIQUE,         -- schema: UQ
    password_hash  VARCHAR(255) NOT NULL,                -- Argon2id hash only
    role           VARCHAR(20)  NOT NULL,
    agency_id      INTEGER REFERENCES agency (agency_id),

    -- domain: role in {CITIZEN, AGENCY_STAFF, REVIEWER, ADMIN}
    CONSTRAINT chk_user_role
        CHECK (role IN ('CITIZEN', 'AGENCY_STAFF', 'REVIEWER', 'ADMIN')),
    -- agency_id is set exactly when role = AGENCY_STAFF
    CONSTRAINT chk_user_agency
        CHECK ((role = 'AGENCY_STAFF') = (agency_id IS NOT NULL)),
    -- stored in lower case so UNIQUE(email) is case-insensitive
    CONSTRAINT chk_user_email_lower
        CHECK (email = lower(email))
);

-- ---------------------------------------------------------------------
-- 3. COMPLAINT                                (ER: entity COMPLAINT)
--    SUBMITS  APP_USER 1 : N COMPLAINT, total on COMPLAINT
--    -> citizen_id NOT NULL.
--    accepted_proposal_id = MongoDB ObjectId (24 hex chars) of the
--    accepted ai_proposals document (DFD 4.4).
-- ---------------------------------------------------------------------
CREATE TABLE complaint (
    complaint_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    citizen_id            INTEGER NOT NULL REFERENCES app_user (user_id),
    description           TEXT NOT NULL,
    created_at            TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    intake_status         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    accepted_proposal_id  VARCHAR(24) UNIQUE,            -- schema: UQ

    -- domain: intake_status in {PENDING, UNDER_REVIEW, ACCEPTED, REJECTED}
    CONSTRAINT chk_complaint_intake
        CHECK (intake_status IN ('PENDING', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED')),
    -- accepted_proposal_id is set exactly when the complaint is ACCEPTED
    CONSTRAINT chk_complaint_accepted
        CHECK ((intake_status = 'ACCEPTED') = (accepted_proposal_id IS NOT NULL)),
    CONSTRAINT chk_complaint_description
        CHECK (length(btrim(description)) > 0)
);

-- ---------------------------------------------------------------------
-- 4. AGENCY_TASK_TYPE          (ER: weak entity, identifying SUPPORTS)
--    PK = owner key agency_id + partial key task_code.
-- ---------------------------------------------------------------------
CREATE TABLE agency_task_type (
    agency_id         INTEGER NOT NULL REFERENCES agency (agency_id),
    task_code         VARCHAR(30) NOT NULL,
    task_description  TEXT,
    sla_hours         INTEGER NOT NULL,
    PRIMARY KEY (agency_id, task_code),
    -- domain: sla_hours > 0
    CONSTRAINT chk_sla_positive CHECK (sla_hours > 0)
);

-- ---------------------------------------------------------------------
-- 5. TASK                                          (ER: entity TASK)
--    GENERATES_TASK  COMPLAINT 1 : N TASK, total on TASK -> NOT NULL
--    DEFINES_TASK    AGENCY_TASK_TYPE 1 : N TASK, total -> NOT NULL,
--                    composite FK (agency_id, task_code).
--    UNIQUE (task_id, complaint_id) is the target of TASK_DEPENDENCY's
--    composite FKs (schema: "Extra UNIQUE").
-- ---------------------------------------------------------------------
CREATE TABLE task (
    task_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  INTEGER NOT NULL REFERENCES complaint (complaint_id),
    agency_id     INTEGER NOT NULL,
    task_code     VARCHAR(30) NOT NULL,
    status        VARCHAR(20) NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    ready_at      TIMESTAMP,
    due_at        TIMESTAMP,
    completed_at  TIMESTAMP,

    CONSTRAINT fk_task_type FOREIGN KEY (agency_id, task_code)
        REFERENCES agency_task_type (agency_id, task_code),
    CONSTRAINT uq_task_complaint UNIQUE (task_id, complaint_id),

    -- domain: the seven task statuses
    CONSTRAINT chk_task_status CHECK (status IN
        ('BLOCKED', 'READY_FOR_DISPATCH', 'IN_PROGRESS', 'COMPLETED',
         'FAILED', 'CANCELLED', 'BLOCKED_EXCEPTION')),
    -- completed_at is set exactly when status = COMPLETED
    CONSTRAINT chk_task_completed
        CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    -- ready_at/due_at: set once a task has been dispatched, empty while
    -- it waits; CANCELLED may be either (it can be cancelled before or
    -- after dispatch)
    CONSTRAINT chk_task_deadline CHECK (
        CASE
            WHEN status IN ('READY_FOR_DISPATCH', 'IN_PROGRESS', 'COMPLETED', 'FAILED')
                THEN ready_at IS NOT NULL AND due_at IS NOT NULL
            WHEN status IN ('BLOCKED', 'BLOCKED_EXCEPTION')
                THEN ready_at IS NULL AND due_at IS NULL
            ELSE TRUE                                   -- CANCELLED
        END),
    CONSTRAINT chk_task_due_after_ready
        CHECK (due_at IS NULL OR due_at > ready_at)
);

-- ---------------------------------------------------------------------
-- 6. TASK_DEPENDENCY   (ER: entity resolving the recursive TASK-TASK
--    relationship via PREREQUISITE_OF and DEPENDENT_OF, total on both)
--    complaint_id is kept on purpose: the composite FKs make it
--    impossible for a task to depend on another complaint's task.
-- ---------------------------------------------------------------------
CREATE TABLE task_dependency (
    prerequisite_task_id  INTEGER NOT NULL,
    dependent_task_id     INTEGER NOT NULL,
    complaint_id          INTEGER NOT NULL,
    PRIMARY KEY (prerequisite_task_id, dependent_task_id),
    CONSTRAINT fk_dep_prerequisite FOREIGN KEY (prerequisite_task_id, complaint_id)
        REFERENCES task (task_id, complaint_id),
    CONSTRAINT fk_dep_dependent FOREIGN KEY (dependent_task_id, complaint_id)
        REFERENCES task (task_id, complaint_id),
    -- schema CHECK: a task cannot depend on itself
    CONSTRAINT chk_dep_not_self CHECK (prerequisite_task_id <> dependent_task_id)
);

-- ---------------------------------------------------------------------
-- 7. AUDIT_LOG                                (ER: entity AUDIT_LOG)
--    PERFORMS, HAS_TASK_AUDIT, HAS_COMPLAINT_AUDIT: all partial
--    -> user_id NULL = automatic change made by a trigger
--    -> task_id and complaint_id both NULL = admin reference-data change
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    audit_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       INTEGER REFERENCES task (task_id),
    complaint_id  INTEGER REFERENCES complaint (complaint_id),
    user_id       INTEGER REFERENCES app_user (user_id),
    action        VARCHAR(30) NOT NULL,
    old_status    VARCHAR(20),
    new_status    VARCHAR(20),
    reason        TEXT,
    created_at    TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    -- schema CHECK: an entry is about a task OR a complaint, never both
    CONSTRAINT chk_audit_target
        CHECK (NOT (complaint_id IS NOT NULL AND task_id IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- Indexes: only for lookups the system performs. PostgreSQL indexes
-- primary keys and UNIQUE columns automatically, but not FK columns.
-- ---------------------------------------------------------------------
CREATE INDEX idx_dep_dependent     ON task_dependency (dependent_task_id); -- "are all prerequisites of this task done?"
CREATE INDEX idx_task_complaint    ON task (complaint_id);                 -- citizen status view (DFD 6.0)
CREATE INDEX idx_task_agency_stat  ON task (agency_id, status);            -- staff ready list (DFD 5.1)
CREATE INDEX idx_audit_task        ON audit_log (task_id);                 -- history views
CREATE INDEX idx_audit_complaint   ON audit_log (complaint_id);
-- The PK (prerequisite_task_id, dependent_task_id) already serves
-- "which tasks wait on the task that just finished?" (DFD 5.3).


-- =====================================================================
-- TRIGGERS - rules a CHECK constraint cannot express
-- =====================================================================

-- ---------------------------------------------------------------------
-- T1. COMPLAINT.citizen_id must be a user whose role is CITIZEN.
--     (A CHECK cannot look at another table.)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_complaint_citizen_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM app_user
                   WHERE user_id = NEW.citizen_id AND role = 'CITIZEN') THEN
        RAISE EXCEPTION 'Only a CITIZEN can own a complaint (user %)', NEW.citizen_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_complaint_citizen_only
    BEFORE INSERT OR UPDATE OF citizen_id ON complaint
    FOR EACH ROW EXECUTE FUNCTION fn_complaint_citizen_only();

-- ---------------------------------------------------------------------
-- T2. Task status rules (BEFORE INSERT / UPDATE OF status).
--
--  a) A new task starts as BLOCKED (has prerequisites) or
--     READY_FOR_DISPATCH (has none)                       - DFD 4.4
--  b) A status change must be one of these 11 allowed transitions
--     (Reconciled Design state diagram; DFD 5.2 - 5.4):
--
--     from                 to                   made by          DFD
--     -------------------  -------------------  ---------------  ----
--     BLOCKED              READY_FOR_DISPATCH   unlock trigger   5.3
--     BLOCKED              BLOCKED_EXCEPTION    unlock trigger   5.3
--     BLOCKED              CANCELLED            reviewer         5.4
--     READY_FOR_DISPATCH   IN_PROGRESS          agency staff     5.2
--     READY_FOR_DISPATCH   CANCELLED            reviewer         5.4
--     IN_PROGRESS          COMPLETED            agency staff     5.2
--     IN_PROGRESS          FAILED               agency staff     5.2
--     FAILED               READY_FOR_DISPATCH   reviewer retry   5.4
--     FAILED               CANCELLED            reviewer cancel  5.4
--     BLOCKED_EXCEPTION    BLOCKED              resolution fn    5.4
--     BLOCKED_EXCEPTION    CANCELLED            reviewer cancel  5.4
--
--     A resolution may chain two of them in one step:
--     BLOCKED_EXCEPTION -> BLOCKED -> READY_FOR_DISPATCH when every
--     prerequisite is already COMPLETED. COMPLETED and CANCELLED are final.
--
--  c) Deadline rule kept in ONE place: whenever a task enters
--     READY_FOR_DISPATCH (at creation, at unlock, or on retry):
--         ready_at = now, due_at = now + sla_hours.
--     Entering BLOCKED / BLOCKED_EXCEPTION clears them; entering
--     COMPLETED stamps completed_at.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_task_status_rules() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_sla INTEGER;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status NOT IN ('BLOCKED', 'READY_FOR_DISPATCH') THEN
            RAISE EXCEPTION 'A new task must start as BLOCKED or READY_FOR_DISPATCH, not %', NEW.status
                USING ERRCODE = 'check_violation';
        END IF;
    ELSE
        IF NEW.status = OLD.status THEN
            RETURN NEW;
        END IF;
        IF (OLD.status, NEW.status) NOT IN (
            ('BLOCKED',            'READY_FOR_DISPATCH'),
            ('BLOCKED',            'BLOCKED_EXCEPTION'),
            ('BLOCKED',            'CANCELLED'),
            ('READY_FOR_DISPATCH', 'IN_PROGRESS'),
            ('READY_FOR_DISPATCH', 'CANCELLED'),
            ('IN_PROGRESS',        'COMPLETED'),
            ('IN_PROGRESS',        'FAILED'),
            ('FAILED',             'READY_FOR_DISPATCH'),
            ('FAILED',             'CANCELLED'),
            ('BLOCKED_EXCEPTION',  'BLOCKED'),
            ('BLOCKED_EXCEPTION',  'CANCELLED')
        ) THEN
            RAISE EXCEPTION 'Illegal task status change % -> % (task %)',
                OLD.status, NEW.status, OLD.task_id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.status = 'READY_FOR_DISPATCH' THEN
        SELECT sla_hours INTO v_sla FROM agency_task_type
         WHERE agency_id = NEW.agency_id AND task_code = NEW.task_code;
        NEW.ready_at := LOCALTIMESTAMP;
        NEW.due_at   := LOCALTIMESTAMP + make_interval(hours => v_sla);
    ELSIF NEW.status IN ('BLOCKED', 'BLOCKED_EXCEPTION') THEN
        NEW.ready_at := NULL;
        NEW.due_at   := NULL;
    ELSIF NEW.status = 'COMPLETED' THEN
        NEW.completed_at := LOCALTIMESTAMP;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_task_status_rules
    BEFORE INSERT OR UPDATE OF status ON task
    FOR EACH ROW EXECUTE FUNCTION fn_task_status_rules();

-- ---------------------------------------------------------------------
-- T3. Unlock trigger (DFD 5.3), AFTER UPDATE OF status.
--     1. find the changed task's dependents
--     2. lock them with SELECT ... FOR UPDATE in task_id order
--        (fixed order = no deadlock)
--     3. in a separate statement, count prerequisites not COMPLETED
--        (a new statement sees work committed while we waited on the lock)
--     4. COMPLETED and count = 0  -> dependent READY_FOR_DISPATCH
--     5. FAILED / CANCELLED / BLOCKED_EXCEPTION
--                                 -> BLOCKED dependents BLOCKED_EXCEPTION
--        (this fires the trigger again on the dependent, so an
--         exception travels down the whole chain)
--     6. audit every automatic change with user_id NULL
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_task_unlock() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_dep      RECORD;
    v_pending  INTEGER;
BEGIN
    FOR v_dep IN
        SELECT t.task_id, t.status
          FROM task t
          JOIN task_dependency d ON d.dependent_task_id = t.task_id
         WHERE d.prerequisite_task_id = NEW.task_id
         ORDER BY t.task_id
           FOR UPDATE OF t
    LOOP
        -- re-read the status after the lock was granted
        SELECT status INTO v_dep.status FROM task WHERE task_id = v_dep.task_id;
        CONTINUE WHEN v_dep.status <> 'BLOCKED';

        IF NEW.status = 'COMPLETED' THEN
            SELECT count(*) INTO v_pending
              FROM task_dependency d
              JOIN task p ON p.task_id = d.prerequisite_task_id
             WHERE d.dependent_task_id = v_dep.task_id
               AND p.status <> 'COMPLETED';

            IF v_pending = 0 THEN
                UPDATE task SET status = 'READY_FOR_DISPATCH'
                 WHERE task_id = v_dep.task_id;
                INSERT INTO audit_log (task_id, action, old_status, new_status, reason)
                VALUES (v_dep.task_id, 'AUTO_UNLOCK', 'BLOCKED', 'READY_FOR_DISPATCH',
                        format('All prerequisites completed (last: task %s)', NEW.task_id));
            END IF;
        ELSE
            UPDATE task SET status = 'BLOCKED_EXCEPTION'
             WHERE task_id = v_dep.task_id;
            INSERT INTO audit_log (task_id, action, old_status, new_status, reason)
            VALUES (v_dep.task_id, 'AUTO_EXCEPTION', 'BLOCKED', 'BLOCKED_EXCEPTION',
                    format('Prerequisite task %s became %s', NEW.task_id, NEW.status));
        END IF;
    END LOOP;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_task_unlock
    AFTER UPDATE OF status ON task
    FOR EACH ROW
    WHEN (OLD.status IS DISTINCT FROM NEW.status
          AND NEW.status IN ('COMPLETED', 'FAILED', 'CANCELLED', 'BLOCKED_EXCEPTION'))
    EXECUTE FUNCTION fn_task_unlock();

-- ---------------------------------------------------------------------
-- T4. Dependencies are fixed once a complaint is ACCEPTED, and a
--     dependent must be waiting (BLOCKED) when its dependency is added.
--     Design: "adding dependencies after acceptance is not allowed".
--     Removing one (waive) stays allowed.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_dependency_insert_rules() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM complaint
               WHERE complaint_id = NEW.complaint_id AND intake_status = 'ACCEPTED') THEN
        RAISE EXCEPTION 'Complaint % is already accepted; dependencies cannot be added',
            NEW.complaint_id USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM task
                   WHERE task_id = NEW.dependent_task_id AND status = 'BLOCKED') THEN
        RAISE EXCEPTION 'Dependent task % must be BLOCKED while it has prerequisites',
            NEW.dependent_task_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_dependency_insert_rules
    BEFORE INSERT ON task_dependency
    FOR EACH ROW EXECUTE FUNCTION fn_dependency_insert_rules();


-- =====================================================================
-- RESOLUTION FUNCTIONS (DFD 5.4, reviewer only; each needs a reason
-- and is audited with the reviewer's user_id). The backend calls these;
-- each runs inside the caller's transaction, so it is all-or-nothing.
-- =====================================================================

-- Re-check one waiting task after a retry or waive. A move back to
-- BLOCKED does not fire the unlock trigger, so this does the check:
--   BLOCKED_EXCEPTION -> BLOCKED  when no prerequisite is FAILED,
--                                 CANCELLED or BLOCKED_EXCEPTION
--   BLOCKED -> READY_FOR_DISPATCH when every prerequisite is COMPLETED
-- If the task left BLOCKED_EXCEPTION, its own dependents are re-checked
-- too, so a whole chain recovers (A -> B -> C).
CREATE OR REPLACE FUNCTION fn_recheck_task(p_task_id INTEGER) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    v_status  VARCHAR(20);
    v_child   INTEGER;
BEGIN
    SELECT status INTO v_status FROM task WHERE task_id = p_task_id FOR UPDATE;

    IF v_status = 'BLOCKED_EXCEPTION' AND NOT EXISTS (
        SELECT 1 FROM task_dependency d JOIN task p ON p.task_id = d.prerequisite_task_id
         WHERE d.dependent_task_id = p_task_id
           AND p.status IN ('FAILED', 'CANCELLED', 'BLOCKED_EXCEPTION')) THEN
        UPDATE task SET status = 'BLOCKED' WHERE task_id = p_task_id;
        INSERT INTO audit_log (task_id, action, old_status, new_status, reason)
        VALUES (p_task_id, 'AUTO_RECOVER', 'BLOCKED_EXCEPTION', 'BLOCKED',
                'No prerequisite is in failure any more');
        v_status := 'BLOCKED';
    END IF;

    IF v_status = 'BLOCKED' AND NOT EXISTS (
        SELECT 1 FROM task_dependency d JOIN task p ON p.task_id = d.prerequisite_task_id
         WHERE d.dependent_task_id = p_task_id
           AND p.status <> 'COMPLETED') THEN
        UPDATE task SET status = 'READY_FOR_DISPATCH' WHERE task_id = p_task_id;
        INSERT INTO audit_log (task_id, action, old_status, new_status, reason)
        VALUES (p_task_id, 'AUTO_UNLOCK', 'BLOCKED', 'READY_FOR_DISPATCH',
                'All remaining prerequisites completed');
        v_status := 'READY_FOR_DISPATCH';
    END IF;

    IF v_status IN ('BLOCKED', 'READY_FOR_DISPATCH') THEN
        FOR v_child IN
            SELECT d.dependent_task_id FROM task_dependency d
              JOIN task c ON c.task_id = d.dependent_task_id
             WHERE d.prerequisite_task_id = p_task_id
               AND c.status = 'BLOCKED_EXCEPTION'
             ORDER BY d.dependent_task_id
        LOOP
            PERFORM fn_recheck_task(v_child);
        END LOOP;
    END IF;
END $$;

CREATE OR REPLACE FUNCTION fn_require_reason(p_reason TEXT) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) < 5 THEN
        RAISE EXCEPTION 'A reason of at least 5 characters is required'
            USING ERRCODE = 'check_violation';
    END IF;
END $$;

-- Retry: FAILED -> READY_FOR_DISPATCH (new deadlines via T2), then
-- re-check every dependent.
CREATE OR REPLACE FUNCTION fn_resolve_retry(p_task_id INTEGER, p_user_id INTEGER, p_reason TEXT)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_dep INTEGER;
BEGIN
    PERFORM fn_require_reason(p_reason);
    IF NOT EXISTS (SELECT 1 FROM task WHERE task_id = p_task_id AND status = 'FAILED') THEN
        RAISE EXCEPTION 'Only a FAILED task can be retried (task %)', p_task_id
            USING ERRCODE = 'check_violation';
    END IF;
    UPDATE task SET status = 'READY_FOR_DISPATCH' WHERE task_id = p_task_id;
    INSERT INTO audit_log (task_id, user_id, action, old_status, new_status, reason)
    VALUES (p_task_id, p_user_id, 'RETRY', 'FAILED', 'READY_FOR_DISPATCH', p_reason);

    FOR v_dep IN SELECT dependent_task_id FROM task_dependency
                  WHERE prerequisite_task_id = p_task_id ORDER BY dependent_task_id
    LOOP
        PERFORM fn_recheck_task(v_dep);
    END LOOP;
END $$;

-- Waive: delete one dependency of a task in BLOCKED_EXCEPTION, then
-- re-check that task.
CREATE OR REPLACE FUNCTION fn_resolve_waive(p_prereq INTEGER, p_dependent INTEGER,
                                            p_user_id INTEGER, p_reason TEXT)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    PERFORM fn_require_reason(p_reason);
    IF NOT EXISTS (SELECT 1 FROM task WHERE task_id = p_dependent
                   AND status = 'BLOCKED_EXCEPTION') THEN
        RAISE EXCEPTION 'Only a task in BLOCKED_EXCEPTION can have a dependency waived'
            USING ERRCODE = 'check_violation';
    END IF;
    DELETE FROM task_dependency
     WHERE prerequisite_task_id = p_prereq AND dependent_task_id = p_dependent;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Task % does not depend on task %', p_dependent, p_prereq;
    END IF;
    INSERT INTO audit_log (task_id, user_id, action, old_status, new_status, reason)
    VALUES (p_dependent, p_user_id, 'WAIVE', 'BLOCKED_EXCEPTION', 'BLOCKED_EXCEPTION',
            format('Waived dependency on task %s: %s', p_prereq, p_reason));
    PERFORM fn_recheck_task(p_dependent);
END $$;

-- Cancel: BLOCKED / READY_FOR_DISPATCH / FAILED / BLOCKED_EXCEPTION -> CANCELLED
-- (FAILED -> CANCELLED closes a task the reviewer decides not to retry,
-- so its complaint can still be resolved)
-- (T2 enforces the allowed sources; T3 passes the exception on).
CREATE OR REPLACE FUNCTION fn_resolve_cancel(p_task_id INTEGER, p_user_id INTEGER, p_reason TEXT)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_old VARCHAR(20);
BEGIN
    PERFORM fn_require_reason(p_reason);
    SELECT status INTO v_old FROM task WHERE task_id = p_task_id FOR UPDATE;
    IF v_old IS NULL THEN
        RAISE EXCEPTION 'Task % does not exist', p_task_id;
    END IF;
    IF v_old = 'CANCELLED' THEN
        RAISE EXCEPTION 'Task % is already cancelled', p_task_id
            USING ERRCODE = 'check_violation';
    END IF;
    UPDATE task SET status = 'CANCELLED' WHERE task_id = p_task_id;
    INSERT INTO audit_log (task_id, user_id, action, old_status, new_status, reason)
    VALUES (p_task_id, p_user_id, 'CANCEL', v_old, 'CANCELLED', p_reason);
END $$;


-- =====================================================================
-- VIEWS - derived values are computed, never stored
-- =====================================================================

-- "Overdue" = due_at has passed and the task is not COMPLETED/CANCELLED.
CREATE VIEW v_task_overdue AS
SELECT t.*, (LOCALTIMESTAMP - t.due_at) AS overdue_by
  FROM task t
 WHERE t.due_at < LOCALTIMESTAMP
   AND t.status NOT IN ('COMPLETED', 'CANCELLED');

-- Overall progress per complaint, derived from its tasks.
-- resolved = it has tasks and all are COMPLETED or CANCELLED.
CREATE VIEW v_complaint_progress AS
SELECT c.complaint_id,
       c.citizen_id,
       c.intake_status,
       count(t.task_id)                                         AS total_tasks,
       count(t.task_id) FILTER (WHERE t.status = 'COMPLETED')   AS completed_tasks,
       count(t.task_id) > 0
         AND bool_and(t.status IN ('COMPLETED', 'CANCELLED'))   AS resolved
  FROM complaint c
  LEFT JOIN task t ON t.complaint_id = c.complaint_id
 GROUP BY c.complaint_id, c.citizen_id, c.intake_status;

